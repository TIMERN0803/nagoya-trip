import asyncio,json,sys
import fulltest as ft
from playwright.async_api import async_playwright
R=[];SH='/home/claude/build/'
def ok(n,c,x=""):R.append((n,bool(c)));print(("PASS " if c else "FAIL ")+n+(" "+str(x) if not c else ""))
async def gohome(pg):
    await pg.click('[data-tab="plan"]');await pg.wait_for_timeout(400)
    if not await pg.query_selector('.g-home'):await pg.click('[data-home]');await pg.wait_for_timeout(400)
async def add_exp(pg,amt,pay):
    await pg.fill('#f-amt',str(amt));await pg.click(f'[data-pick="pay"] [data-v="{pay}"]')
    await pg.click('#f-save');await pg.wait_for_timeout(400)
async def wallet_set(pg,mode,v):
    await pg.click('.wchip');await pg.wait_for_timeout(250)
    if await pg.locator('.ws [data-wallet-edit]').count():await pg.click(f'.ws [data-wallet-edit][data-mode="{mode}"]');await pg.wait_for_timeout(150)
    await pg.fill('.ws .w-form input',str(v));await pg.click('.ws .w-form .primary');await pg.wait_for_timeout(400)
async def close(pg):
    await pg.click('.ws .sm-x');await pg.wait_for_timeout(200)
async def main(shots=True):
    async with async_playwright() as p:
        b=await p.chromium.launch()
        ctx=await b.new_context(viewport={'width':390,'height':844},device_scale_factor=2,timezone_id="Asia/Tokyo")
        await ctx.route("**/firebasejs/**/firebase-app.js",lambda r:r.fulfill(body=ft.APP,content_type="text/javascript",headers={"access-control-allow-origin":"*"}))
        await ctx.route("**/firebasejs/**/firebase-firestore.js",lambda r:r.fulfill(body=ft.FS,content_type="text/javascript",headers={"access-control-allow-origin":"*"}))
        await ctx.route("**/fonts.googleapis.com/**",lambda r:r.abort())
        await ctx.route("**/api.open-meteo.com/**",lambda r:r.abort())
        pg0=await ft.newpage(b,ft.jst(11,19,12,9),me=None,ctx=ctx)
        await pg0.click('[data-tab="acct"]');await pg0.wait_for_timeout(500)
        ok("no wallet box on page",await pg0.locator('#acct-wallet').count()==0)
        ok("chip says 設定錢包","設定錢包" in await pg0.inner_text('.wchip'))
        if shots:await pg0.screenshot(path=SH+'ws_bar0.png',clip={'x':0,'y':0,'width':390,'height':120})
        await pg0.click('.wchip');await pg0.wait_for_timeout(300)
        ok("sheet asks who",await pg0.locator('.ws [data-wallet-me]').count()==2)
        if shots:await pg0.screenshot(path=SH+'ws_who.png')
        await pg0.click('.ws [data-wallet-me="zhang"]');await pg0.wait_for_timeout(300)
        ok("picked: saved",await pg0.evaluate('localStorage.getItem("ngy:me")')=="zhang")
        ok("picked: set form shown",await pg0.locator('.ws .w-form input').count()==1)
        ok("picked: form payer zhang",await pg0.get_attribute('[data-pick="who"] [data-v="zhang"]','aria-pressed')=="true")
        if shots:await pg0.screenshot(path=SH+'ws_set.png')
        await pg0.close()
        pg=await ft.newpage(b,ft.jst(11,19,12,10),ctx=ctx)
        await pg.click('[data-tab="acct"]');await pg.wait_for_timeout(500)
        ok("pay pick default cash",await pg.get_attribute('[data-pick="pay"] [data-v="cash"]','aria-pressed')=="true")
        await wallet_set(pg,"set",40000)
        ok("set 40000","¥40,000" in await pg.inner_text('.ws-hero'))
        ok("chip updates","¥40,000" in await pg.inner_text('.wchip'))
        await close(pg)
        ok("sheet closed",await pg.locator('.ws').count()==0)
        await add_exp(pg,3000,"cash");await add_exp(pg,8000,"card")
        ok("cash deducted only cash","¥37,000" in await pg.inner_text('.wchip'))
        lt=await pg.inner_text('#acct-list');ok("row says 付現/刷卡","付現" in lt and "刷卡" in lt)
        await wallet_set(pg,"add",10000)
        t=await pg.inner_text('.ws-hero')
        ok("top-up adds","¥47,000" in t and "換了 ¥50,000" in t,t)
        await pg.click('.ws [data-wallet-edit][data-mode="set"]');await pg.wait_for_timeout(150)
        await pg.click('.ws [data-wmode="add"]');await pg.wait_for_timeout(150)
        ok("mode toggle works",await pg.get_attribute('.ws [data-wmode="add"]','aria-pressed')=="true" and "加進錢包" in await pg.inner_text('.ws .w-form .primary'))
        await pg.click('.ws [data-wallet-cancel]');await pg.wait_for_timeout(150)
        ok("only my wallet editable",await pg.locator('.ws .w-row [data-wallet-edit]').count()==0)
        if shots:await pg.screenshot(path=SH+'ws_main.png')
        stored=await pg.evaluate('JSON.parse(localStorage.getItem("mockdb")||"{}")["trips/neko-test/wallet/zhang"]')
        ok("saved to firestore",stored and stored.get("cashIn")==50000,stored)
        await pg.mouse.click(200,60);await pg.wait_for_timeout(200)
        ok("backdrop closes",await pg.locator('.ws').count()==0)
        if shots:await pg.screenshot(path=SH+'ws_bar.png',clip={'x':0,'y':0,'width':390,'height':120})
        await add_exp(pg,43000,"cash")
        ok("chip low",await pg.locator('.wchip.low').count()==1)
        await pg.click('.wchip');await pg.wait_for_timeout(250)
        ok("hero low",await pg.locator('.ws-hero.low').count()==1)
        if shots:await pg.screenshot(path=SH+'ws_low.png')
        await close(pg)
        await gohome(pg)
        ok("home pill shows cash","¥4,000" in await pg.inner_text('.hp-yen'))
        await pg.click('.hp-yen');await pg.wait_for_timeout(250)
        ok("home pill opens sheet",await pg.locator('.ws').count()==1)
        await close(pg)
        pg2=await ft.newpage(b,ft.jst(11,19,12,11),me="star",ctx=ctx)
        await pg2.click('[data-tab="acct"]');await pg2.wait_for_timeout(500)
        await pg2.click('.wchip');await pg2.wait_for_timeout(250)
        t2=await pg2.inner_text('.ws .w-row')
        ok("partner sees my wallet","¥4,000" in t2,t2)
        ok("partner sheet edits own (set form)",await pg2.locator('.ws .w-form').count()==1)
        await pg2.click('.ws .sm-x')
        await gohome(pg2)
        ok("partner home pill falls back",await pg2.locator('.hp-yen use[href="#t-acct"]').count()==1)
        ok("no js errors",not pg.errs and not pg2.errs,pg.errs+pg2.errs)
        await b.close()
    f=[n for n,c in R if not c];print(f"{len(R)-len(f)}/{len(R)} passed",f);sys.exit(1 if f else 0)
asyncio.run(main("--noshot" not in sys.argv))
