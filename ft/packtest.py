import asyncio,json
import fulltest as ft
from playwright.async_api import async_playwright
base="trips/neko-test"
async def main():
    async with async_playwright() as p:
        b=await p.chromium.launch()
        # upgrade case: server already seeded v1, user deleted "mu" and "b5"
        srv={f"{base}/items/{k}":{"group":g,"title":k,"order":i} for i,(k,g) in enumerate([("vjw","prep"),("seat1","prep"),("kiso","prep"),("seat2","prep"),("b1","buy"),("b2","buy"),("b3","buy"),("b4","buy")])}
        srv[f"{base}/settings/meta"]={"itemsSeeded":True,"itemsRestore":1}
        ctx=await b.new_context(viewport={'width':390,'height':844},device_scale_factor=2,timezone_id="Asia/Taipei")
        await ctx.route("**/firebasejs/**/firebase-app.js",lambda r:r.fulfill(body=ft.APP,content_type="text/javascript",headers={"access-control-allow-origin":"*"}))
        await ctx.route("**/firebasejs/**/firebase-firestore.js",lambda r:r.fulfill(body=ft.FS,content_type="text/javascript",headers={"access-control-allow-origin":"*"}))
        await ctx.route("**/api.open-meteo.com/**",lambda r:r.abort())
        a=await ft.newpage(b,ft.twt(10,25,10),ctx=ctx,init=f'localStorage.setItem("mockdb",{json.dumps(json.dumps(srv))});')
        await a.wait_for_timeout(1500)
        db=await a.evaluate('JSON.parse(localStorage.getItem("mockdb"))')
        packs=[k for k,v in db.items() if "/items/" in k and v.get("group")=="pack"]
        ft.rec("行李","升級：自動加上 25 項行李清單",len(packs)==25,len(packs))
        ft.rec("行李","升級：使用者刪掉的待辦和要買的不會被加回來",f"{base}/items/mu" not in db and f"{base}/items/b5" not in db)
        ft.rec("行李","升級標記改成第 2 版",db.get(f"{base}/settings/meta",{}).get("itemsRestore")==2)
        await a.click('nav.tabs button[data-tab="list"]');await a.wait_for_timeout(500)
        top=await a.evaluate('document.querySelector(".stack").firstElementChild.className')
        ft.rec("行李","清單頁最上方是行李入口卡",top=="pack-entry",top)
        await a.screenshot(path='/home/claude/build/pack_entry.png')
        await a.click('[data-pack-open]');await a.wait_for_timeout(500)
        bar=await a.evaluate('document.querySelector(".bar").innerText.replace(/\\s+/g," ")')
        ft.rec("行李","共用狀態在標題同一列","同步中" in bar,bar)
        n=await a.evaluate('document.querySelectorAll(".pack-row").length')
        ft.rec("行李","行李內頁顯示 25 項",n==25,n)
        await a.evaluate('document.querySelector(".group.pack").scrollIntoView()');await a.wait_for_timeout(300)
        await a.click('.pack-row >> nth=0 >> [data-who="zhang"]');await a.wait_for_timeout(300)
        await a.click('.pack-row >> nth=2 >> [data-who="zhang"]');await a.wait_for_timeout(300)
        other=await a.evaluate('document.querySelector(".pack-row [disabled].pk")!==null')
        ft.rec("行李","只能勾自己的，對方的按鈕是唯讀",other)
        db=await a.evaluate('JSON.parse(localStorage.getItem("mockdb"))')
        ft.rec("行李","阿彰的勾選存到雲端（分開記錄）",db.get(f"{base}/checks/k01@zhang",{}).get("done") is True and f"{base}/checks/k01@star" not in db)
        prog=await a.evaluate('document.querySelector(".pack-sum").innerText.replace(/\\s+/g," ")')
        ft.rec("行李","上方顯示兩人各自進度","2/25" in prog and "0/25" in prog,prog)
        cats=await a.evaluate('[...document.querySelectorAll(".group.pack h3")].map(h=>h.innerText.replace(/\\s+/g," "))')
        ft.rec("行李","分成六類並顯示自己的進度",len(cats)==6 and cats[0].startswith("證件與錢"),cats)
        await a.evaluate('scrollTo(0,0)');await a.wait_for_timeout(200);await a.screenshot(path='/home/claude/build/pack_page.png')
        await a.click('[data-pack-todo]');await a.wait_for_timeout(300)
        n3=await a.evaluate('document.querySelectorAll(".pack-row").length')
        ft.rec("行李","只看我還沒裝的：剩 23 項",n3==23,n3)
        await a.screenshot(path='/home/claude/build/pack_todo.png')
        await a.click('[data-pack-todo]');await a.wait_for_timeout(300)
        await a.evaluate('document.querySelector(".group.pack").scrollIntoView()');await a.wait_for_timeout(300)
        await a.screenshot(path='/home/claude/build/pack_zhang.png')
