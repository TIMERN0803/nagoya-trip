# 退稅流程（新制）說明面板測試：三個入口、四個階段分頁（打開停在現在那段）、內容、鍵盤、關閉與焦點、看退稅清單、窄螢幕
import asyncio,json
import fulltest as ft
from playwright.async_api import async_playwright
B="trips/neko-tr"
DB=json.dumps({f"{B}/expenses/a":{"amt":13200,"cat":"shop","who":"zhang","split":"self","pay":"card","day":"11/21","note":"大國藥妝","ts":1,"tf":True}})
SH='.sheet-modal:not(.leaving) .tr-sheet'
async def opened(pg):return await pg.query_selector(SH) is not None
async def sel(pg):return await pg.evaluate('document.querySelector(".tr-sheet [data-tr-tab][aria-selected=true]")?.dataset.trTab')
async def panel(pg):return await pg.inner_text(SH+' .tr-panel')
async def main():
    async with async_playwright() as p:
        b=await p.chromium.launch()
        a=await ft.newpage(b,ft.jst(11,21,20,0),me="zhang",code="neko-tr",init=f'localStorage.setItem("mockdb",{json.dumps(DB)});')
        await a.evaluate('document.querySelector(".tabs [data-tab=list]").click()');await a.wait_for_timeout(400)
        await a.click('[data-list-tab="buy"]');await a.wait_for_timeout(300)
        ft.rec("退稅流程","要買的免稅提醒有「退稅怎麼辦」",await a.query_selector('.tf-tip [data-tr-open]') is not None)
        await a.click('.tf-tip [data-tr-open]');await a.wait_for_timeout(650)
        ft.rec("退稅流程","從要買的打開面板",await opened(a))
        ft.rec("退稅流程","四個分頁：買東西、前一晚、機場、回家",await a.evaluate('[...document.querySelectorAll(".tr-sheet [data-tr-tab]")].map(e=>e.querySelector("b").textContent).join()')=="買東西,前一晚,機場,回家")
        ft.rec("退稅流程","11/21 停在「買東西」，標「現在」",await sel(a)=="shop" and await a.evaluate('document.querySelector(".tr-sheet [data-tr-tab=shop] small.now")?.textContent')=="現在")
        ft.rec("退稅流程","分頁的 ARIA：只有選中的可 Tab 進入",await a.evaluate('[...document.querySelectorAll(".tr-sheet [data-tr-tab]")].map(b=>b.tabIndex).join()')=="0,-1,-1,-1" and await a.evaluate('document.getElementById("tr-panel").getAttribute("role")')=="tabpanel")
        t=await panel(a)
        for k in ["先付含稅價，海關確認後才退錢","稅前 ¥5,000","90 天內出境","menzei tetsuzuki","刷卡選日圓","分開結帳"]:ft.rec("退稅流程",f"買東西有「{k}」",k in t)
        ft.rec("退稅流程","每一步都是標題＋一句話",await a.evaluate('[...document.querySelectorAll(".tr-sheet .tr-steps>li>small")].every(x=>x.textContent.length<=24)'))
        ft.rec("退稅流程","細節預設收起來","NT$300" not in t)
        await a.click(SH+' .tr-d summary');ft.rec("退稅流程","點「看細節」展開","NT$300–400" in await panel(a) and "收起來" in await a.inner_text(SH+' .tr-d summary'))
        ft.rec("退稅流程","「整張退不到」預設收起來","退款的卡號" not in await panel(a))
        await a.click(SH+' .tr-lose summary');ft.rec("退稅流程","點開「整張退不到」","先託運了才想到要辦" in await panel(a))
        h0=await a.evaluate('document.querySelector(".tr-sheet").getBoundingClientRect().height')
        await a.click(SH+' [data-tr-tab=fly]');await a.wait_for_timeout(150)
        t=await panel(a)
        ft.rec("退稅流程","點「機場」換內容",await sel(a)=="fly" and "託運之後就不能辦了" in t and "刷卡選日圓" not in t)
        for k in ["Customs_WiFi_For_TaxRefund","jcustoms","退稅手續","綠色","紅色","照常託運"]:ft.rec("退稅流程",f"機場有「{k}」",k in t)
        ft.rec("退稅流程","換分頁面板高度不跳",abs(await a.evaluate('document.querySelector(".tr-sheet").getBoundingClientRect().height')-h0)<2)
        await a.focus(SH+' [data-tr-tab=fly]');await a.keyboard.press("ArrowRight")
        ft.rec("退稅流程","→ 鍵切到「回家」、焦點跟著",await sel(a)=="home" and await a.evaluate('document.activeElement.dataset.trTab')=="home" and "等退款入帳" in await panel(a))
        await a.keyboard.press("ArrowRight");ft.rec("退稅流程","最後一個再按 → 回到第一個",await sel(a)=="shop")
        await a.keyboard.press("End");ft.rec("退稅流程","End 到最後",await sel(a)=="home")
        await a.keyboard.press("Home");ft.rec("退稅流程","Home 到第一個",await sel(a)=="shop")
        ft.rec("退稅流程","外部連結另開分頁",await a.evaluate('[...document.querySelectorAll(".tr-sheet a[href^=http]")].every(x=>x.target==="_blank"&&x.rel.includes("noopener"))'))
        await a.keyboard.press("Escape");await a.wait_for_timeout(400)
        ft.rec("退稅流程","Esc 關閉，焦點回到入口",not await opened(a) and await a.evaluate('document.activeElement&&document.activeElement.matches("[data-tr-open]")'))
        await a.click('nav.tabs button[data-tab="acct"]');await a.wait_for_timeout(500)
        ft.rec("退稅流程","記帳的退稅清單底部有入口",await a.query_selector('#tf-list .tr-more[data-tr-open]') is not None)
        await a.click('#tf-list [data-tr-open]');await a.wait_for_timeout(650)
        ft.rec("退稅流程","從記帳打開面板",await opened(a))
        await a.click('.sheet-modal',position={"x":20,"y":20});await a.wait_for_timeout(400)
        ft.rec("退稅流程","點背景關閉",not await opened(a) and await a.evaluate('document.body.style.overflow===""'))
        # 11/24：行程入口，停在機場
        d=await ft.newpage(b,ft.jst(11,24,7,30),me="zhang",code="neko-tr",init=f'localStorage.setItem("mockdb",{json.dumps(DB)});')
        await d.wait_for_timeout(400)
        ft.rec("退稅流程","11/24 行程有「退稅怎麼辦」",await d.query_selector('ol.tl [data-tr-open]') is not None)
        await d.click('ol.tl [data-tr-open]');await d.wait_for_timeout(650)
        ft.rec("退稅流程","11/24 打開停在「機場」",await sel(d)=="fly" and "Customs_WiFi_For_TaxRefund" in await panel(d))
        await d.click(SH+' [data-tr-tab=pack]')
        await d.click(SH+' [data-go-tf]');await d.wait_for_timeout(700)
        ft.rec("退稅流程","前一晚的「看退稅清單」關閉面板並切到記帳",not await opened(d) and await d.query_selector('#tf-list:not([hidden])') is not None and await d.evaluate('document.body.style.overflow===""'))
        for day,hh,want,nm in [(10,12,"shop","出發前先看「買東西」"),(23,21,"pack","11/23 停在「前一晚」"),(26,12,"home","回國後停在「回家」")]:
            e=await ft.newpage(b,ft.jst(11,day,hh,0),me="zhang",code="neko-tr",ctx=a.ctx)
            await e.evaluate('openTrSheet()');await e.wait_for_timeout(650)
            ft.rec("退稅流程",nm,await sel(e)==want)
            if want=="pack":
                await e.set_viewport_size({"width":320,"height":640});await e.wait_for_timeout(300)
                ft.rec("退稅流程","320 寬度：面板不橫向捲動、分頁字沒被裁",await e.evaluate('(()=>{const c=document.querySelector(".tr-sheet");return c.scrollWidth<=c.clientWidth+1&&[...c.querySelectorAll(".tr-tab")].every(t=>t.scrollWidth<=t.clientWidth+1)})()'))
                ft.rec("退稅流程","320 寬度：分頁可點範圍至少 44 高",await e.evaluate('[...document.querySelectorAll(".tr-tab")].every(t=>t.getBoundingClientRect().height>=44)'))
            await e.close()
        errs=a.errs+d.errs
        ft.rec("退稅流程","沒有錯誤",not errs,errs[:3])
        await b.close()
    bad=[r for r in ft.R if not r[2]];print("TOTAL",len(ft.R),"FAIL",len(bad))
asyncio.run(main())
